import React, { useState } from 'react';
import { CareerMatchReport } from '../types';
import { X, Printer, Download, Copy, Check, FileText } from 'lucide-react';

interface ExportReportModalProps {
  report: CareerMatchReport;
  onClose: () => void;
}

export const ExportReportModal: React.FC<ExportReportModalProps> = ({ report, onClose }) => {
  const [copiedMd, setCopiedMd] = useState(false);

  const generateMarkdown = () => {
    return `# CareerMatch AI 2 - Comprehensive Job-Fit & Interview Prep Report
**Target Role:** ${report.overview.targetRole}  
**Company:** ${report.overview.company}  
**Date:** ${new Date().toLocaleDateString()}  
**Job Fit Score:** ${report.overview.jobFitScore}/100  
**ATS Score:** ${report.overview.atsScore}/100  
**Interview Readiness:** ${report.overview.interviewReadinessScore}/100  

---

## 1. Executive Overview
${report.overview.roleSummary}

### Top Strengths
${report.overview.topStrengths
  .map((s) => `- **[${s.badge}] ${s.title}:** ${s.detail} *(Proof: ${s.evidence || 'N/A'})*`)
  .join('\n')}

### Gaps to Address
${report.overview.gapsToAddress
  .map((g) => `- **[${g.severity.toUpperCase()}] ${g.title}:** ${g.detail} \`${g.addPlaceholder || ''}\``)
  .join('\n')}

---

## 2. Fit Score Analysis
- **Verdict:** ${report.fitScore.verdict}
- **Percentile:** ${report.fitScore.percentileRank}
- **Key Takeaway:** ${report.fitScore.keyTakeaway}

### Weighted Breakdown
${report.fitScore.dimensionScores
  .map((d) => `- **${d.category}** (${d.weight}): ${d.score}/${d.maxScore} pts - ${d.rationale}`)
  .join('\n')}

---

## 3. CV Optimization (Google XYZ Formula)
**Overview:** ${report.cvOptimizer.optimizationOverview}  
**Tailored Bio:**  
> "${report.cvOptimizer.tailoredExecutiveBio}"

### Bullet Upgrades
${report.cvOptimizer.bulletRevisions
  .map(
    (b) =>
      `#### ${b.context} (${b.framework})\n- **Before:** ~${b.originalBullet}~\n- **After:** **${b.optimizedBullet}**\n- *Metric Added:* ${b.metricAdded}`
  )
  .join('\n\n')}

---

## 4. Model Interview Questions & STAR Answers
${report.interviewQuestions.technical
  .map(
    (t, idx) => `### Technical Q${idx + 1}: ${t.question}
**Interviewer Goal:** ${t.whyAsked}  
**Expected Depth:** ${t.interviewerExpectedDepth}  
- **[S] Situation:** ${t.recommendedStarAnswer.situation}
- **[T] Task:** ${t.recommendedStarAnswer.task}
- **[A] Action:** ${t.recommendedStarAnswer.action}
- **[R] Result:** ${t.recommendedStarAnswer.result}  
**Trap to Avoid:** ${t.redFlagsToAvoid}
`
  )
  .join('\n\n')}

---

## 5. Case Interview Prep
**Scenario:** ${report.caseInterviewPrep.scenarioTitle}  
**Problem:** ${report.caseInterviewPrep.businessProblem}  
**Key Framework:**  
${report.caseInterviewPrep.architectureFramework.map((f) => `- ${f}`).join('\n')}

---

## 6. Story Bank & Pitches
### 30-Second Elevator Pitch
> "${report.storyBank.elevatorPitch30s}"

### 60-Second Executive Pitch
> "${report.storyBank.elevatorPitch60s}"

### Why This Company?
> "${report.storyBank.whyThisCompanyPitch}"

---

## 7. 7-Day Sprint Preparation Plan
${report.prepPlan.dailyPlan
  .map(
    (d) =>
      `### Day ${d.dayNumber}: ${d.title} (Milestone: ${d.dailyMilestone})\n` +
      d.actionItems.map((a) => `- [ ] ${a.description} (${a.durationMinutes} min)`).join('\n')
  )
  .join('\n\n')}

---
*Generated by CareerMatch AI 2. Fit scores are AI decision-support estimates.*
`;
  };

  const handlePrint = () => {
    window.print();
  };

  const handleDownloadMarkdown = () => {
    const md = generateMarkdown();
    const blob = new Blob([md], { type: 'text/markdown;charset=utf-8;' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.setAttribute('download', `CareerMatch_${report.overview.company.replace(/\s+/g, '_')}_Report.md`);
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
  };

  const handleDownloadJson = () => {
    const blob = new Blob([JSON.stringify(report, null, 2)], { type: 'application/json' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.setAttribute('download', `CareerMatch_${report.overview.company.replace(/\s+/g, '_')}_Data.json`);
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
  };

  const handleCopyMarkdown = () => {
    navigator.clipboard.writeText(generateMarkdown());
    setCopiedMd(true);
    setTimeout(() => setCopiedMd(false), 2000);
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/80 backdrop-blur-xs">
      <div className="bg-[#0a1514] border border-[#1b3e37] rounded-2xl w-full max-w-4xl max-h-[90vh] flex flex-col shadow-2xl overflow-hidden animate-fadeIn">
        {/* Modal Header */}
        <div className="p-5 border-b border-[#142925] flex items-center justify-between bg-[#0c1a17]">
          <div className="flex items-center gap-2.5">
            <div className="w-8 h-8 rounded-lg bg-[#2dd4bf] text-[#062420] flex items-center justify-center font-bold">
              <FileText className="w-4 h-4 stroke-[2.5]" />
            </div>
            <div>
              <h3 className="text-base font-bold text-white">Export Preparation Dossier</h3>
              <p className="text-xs text-gray-400">
                {report.overview.targetRole} • {report.overview.company}
              </p>
            </div>
          </div>

          <button
            onClick={onClose}
            className="p-1.5 rounded-lg text-gray-400 hover:text-white hover:bg-[#142925] transition-colors"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Action Bar */}
        <div className="p-4 bg-[#091513] border-b border-[#142925] flex flex-wrap items-center gap-3">
          <button
            onClick={handlePrint}
            className="flex items-center gap-2 bg-[#2dd4bf] hover:bg-[#3bf4dc] text-[#05231e] font-semibold text-xs px-3.5 py-2 rounded-lg transition-all shadow-sm cursor-pointer"
          >
            <Printer className="w-3.5 h-3.5" />
            <span>Print / Save as PDF</span>
          </button>

          <button
            onClick={handleDownloadMarkdown}
            className="flex items-center gap-2 bg-[#0e211e] hover:bg-[#16342e] border border-[#1b433a] text-gray-200 hover:text-white text-xs font-medium px-3.5 py-2 rounded-lg transition-colors cursor-pointer"
          >
            <Download className="w-3.5 h-3.5 text-teal-400" />
            <span>Download Markdown (.md)</span>
          </button>

          <button
            onClick={handleDownloadJson}
            className="flex items-center gap-2 bg-[#0e211e] hover:bg-[#16342e] border border-[#1b433a] text-gray-200 hover:text-white text-xs font-medium px-3.5 py-2 rounded-lg transition-colors cursor-pointer"
          >
            <Download className="w-3.5 h-3.5 text-teal-400" />
            <span>Download JSON Data</span>
          </button>

          <button
            onClick={handleCopyMarkdown}
            className="flex items-center gap-2 bg-[#0e211e] hover:bg-[#16342e] border border-[#1b433a] text-gray-200 hover:text-white text-xs font-medium px-3.5 py-2 rounded-lg transition-colors ml-auto cursor-pointer"
          >
            {copiedMd ? (
              <>
                <Check className="w-3.5 h-3.5 text-emerald-400" />
                <span className="text-emerald-400">Copied</span>
              </>
            ) : (
              <>
                <Copy className="w-3.5 h-3.5" />
                <span>Copy Markdown</span>
              </>
            )}
          </button>
        </div>

        {/* Preview Scroll area */}
        <div className="p-6 overflow-y-auto flex-1 text-xs text-gray-300 font-mono leading-relaxed bg-[#06100f] select-text">
          <pre className="whitespace-pre-wrap font-sans text-gray-200">
            {generateMarkdown()}
          </pre>
        </div>
      </div>
    </div>
  );
};
